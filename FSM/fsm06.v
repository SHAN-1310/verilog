module fsm06(
input clk,reset,in,
output reg disc,flag,error);
parameter NONE=4'b0000,
ONE=4'b0001,
TWO=4'b0010,
THREE=4'b0011,
FOUR=4'b0100,
FIVE=4'b0101,
SIX=4'b0110,
ERROR=4'b0111,
DISCARD=4'b1000,
FLAG=4'b1001;
reg[9:0]state,next_state;
always@(posedge clk) begin
if(reset)
state<=NONE;
else
state<=next_state;
end
always@(*) begin
case(state)
NONE:begin
if(in)
next_state=ONE;
else
next_state=NONE;
end
ONE:begin
if(in)
next_state=TWO;
else
next_state=NONE;
end
TWO:begin
if(in)
next_state=THREE;
else
next_state=NONE;
end
THREE:begin
if(in)
next_state=FOUR;
else
next_state=NONE;
end
FOUR:begin
if(in)
next_state=FIVE;
else
next_state=NONE;
end
FIVE:begin
if(in)
next_state=SIX;
else
next_state=DISCARD;
end
SIX:begin
if(in)
next_state=ERROR;
else
next_state=FLAG;
end
ERROR:begin
if(in)
next_state=ERROR;
else
next_state=NONE;
end
DISCARD:begin
if(in)
next_state=ONE;
else
next_state=NONE;
end
FLAG:begin
if(in)
next_state=ONE;
else
next_state=NONE;
end
default:next_state=NONE;
endcase
end
always@(*) begin
disc=(state==DISCARD);
flag=(state==FLAG);
error=(state==ERROR);
end
endmodule
